from reportlab.platypus import SimpleDocTemplate, Paragraph
from reportlab.lib.styles import getSampleStyleSheet
import os

def generate_pdf_report(df, cleaned_df, filename="reports/AI_Data_Detective_Report.pdf"):

    os.makedirs("reports", exist_ok=True)

    doc = SimpleDocTemplate(filename)
    styles = getSampleStyleSheet()
    story = []

    story.append(Paragraph("<b>AI Data Detective Report</b>", styles["Title"]))
    story.append(Paragraph("<br/>", styles["Normal"]))

    story.append(Paragraph(f"Total Rows: {len(df)}", styles["Normal"]))
    story.append(Paragraph(f"Total Columns: {len(df.columns)}", styles["Normal"]))

    missing_before = df.isnull().sum().sum()
    duplicate_before = df.duplicated().sum()

    story.append(Paragraph(f"Missing Values Found: {missing_before}", styles["Normal"]))
    story.append(Paragraph(f"Duplicate Rows Found: {duplicate_before}", styles["Normal"]))

    story.append(Paragraph("<br/>Dataset cleaned successfully.", styles["Normal"]))
    story.append(Paragraph("Generated by AI Data Detective", styles["Normal"]))

    doc.build(story)

    return filename